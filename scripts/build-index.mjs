import { readFileSync, writeFileSync } from 'node:fs';
import { validateCatalog } from './validate.mjs';

const catalog = JSON.parse(readFileSync(new URL('../data/places.json', import.meta.url)));
const errors = validateCatalog(catalog);
if (errors.length) throw new Error(errors.join('\n'));
const sources = new Map(catalog.sources.map(s => [s.id, s]));
const esc = text => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
const label = text => text.replaceAll('_', ' ').replaceAll('-', ' ');
const primary = p => p.locations.find(l => l.id === p.primary_location_id);
const citations = ids => [...new Set(ids)].map(id => {
  const s = sources.get(id);
  return `[${esc(s.title)}${s.published_on ? ` (${s.published_on})` : ''}](${s.url})`;
}).join('; ');
const locationNames = (p, ids) => ids.map(id => p.locations.find(l => l.id === id).address.street_address).join('; ');
function hoursText(hours) {
  const days = Object.entries(hours.weekly);
  const format = periods => periods === null ? 'unknown' : periods.length === 0 ? 'closed' : periods.map(w => `${w.opens}–${w.closes}${w.closes_next_day ? ' (+1 day)' : ''}`).join(', ');
  const groups = [];
  for (const [day, periods] of days) {
    const value = format(periods);
    const shortDay = day.slice(0,3);
    if (groups.length && groups.at(-1).value === value) groups.at(-1).last = shortDay;
    else groups.push({ first:shortDay, last:shortDay, value });
  }
  return groups.map(g => `${g.first === g.last ? g.first : `${g.first}–${g.last}`} ${g.value}`).join('; ');
}

const lines = [
  '# San Francisco burrito catalog', '',
  '<!-- Generated by npm run build:index. Edit data/places.json, not this file. -->', '',
  `Research snapshot: **${catalog.updated_on}**. Source publication dates may be older.`, '',
  '[JSON data](data/places.json) · [Schema](schema/catalog.schema.json) · [Methodology and usage](README.md)', '',
  'The catalog includes strong critical picks and broader neighborhood candidates. Evidence labels distinguish them. No numerical ranking is implied. Watchlist entries are not current recommendations.', '',
  'Hours are posted schedules in San Francisco time. **(+1 day)** means the following calendar day. **Unknown** is not closed. Ordering windows may differ from walk-in service.', '',
  '## Index', '',
  '| Place | Primary neighborhood | Styles | Evidence | Status |',
  '| --- | --- | --- | --- | --- |',
];
const sorted = [...catalog.places].sort((a,b) => a.name.localeCompare(b.name));
for (const p of sorted) lines.push(`| [${esc(p.name)}](#${p.id})${p.shortlist ? ' ★' : ''} | ${esc(primary(p).neighborhood)} | ${p.styles.map(label).join(', ')} | ${[...new Set(p.reviews.map(r => label(r.evidence)))].join('; ')} | ${p.status} |`);
lines.push('', '★ = starting shortlist for variety, not a ranked score.', '');
for (const p of sorted) {
  lines.push(`<a id="${p.id}"></a>`, '', `## ${p.name}`, '', p.summary, '', `**Styles:** ${p.styles.map(label).join(', ')}. **Status:** ${p.status}.`, '', `**Vibe:** ${p.vibe.summary ?? 'Not established.'} (${label(p.vibe.basis)}; applies to ${locationNames(p,p.vibe.location_ids)}).`, '');
  if (p.vibe.source_ids.length) lines.push(`Vibe evidence: ${citations(p.vibe.source_ids)}.`, '');
  lines.push('**Orders to consider**', '');
  for (const item of p.standout_items) lines.push(`- **${item.name}** — ${label(item.basis)}; ${locationNames(p,item.location_ids)}. ${item.notes.join(' ')} ${citations(item.source_ids)}.`);
  lines.push('', '**Review evidence**', '');
  for (const review of p.reviews) lines.push(`- **${label(review.evidence)}** — ${locationNames(p,review.location_ids)}. ${review.summary} ${citations(review.source_ids)}.`);
  lines.push('', '**Locations and posted hours**', '', '| Location | Status | Hours | Schedule type | Sources |', '| --- | --- | --- | --- | --- |');
  for (const loc of p.locations) lines.push(`| [${esc(loc.address.street_address)}](${loc.maps_url}), ${esc(loc.neighborhood)} | ${loc.operating_status} | ${hoursText(loc.hours)} | ${label(loc.hours.scope)}; ${loc.hours.status} | ${citations(loc.hours.source_ids.length ? loc.hours.source_ids : loc.source_ids)} |`);
  lines.push('');
  for (const loc of p.locations) for (const note of [...loc.notes,...loc.hours.notes]) lines.push(`- **${loc.address.street_address}:** ${note}`);
  if (p.visit_notes.length) { lines.push('', '**Visit notes**', ''); for (const n of p.visit_notes) lines.push(`- ${n}`); }
  if (p.research_gaps.length) { lines.push('', '**Research gaps**', ''); for (const n of p.research_gaps) lines.push(`- ${n}`); }
  lines.push('', `[Back to index](#index) · Last researched ${p.checked_on}`, '');
}
lines.push('## Excluded pending confirmation', '');
for (const e of catalog.exclusions) lines.push(`- **${e.name}:** ${e.reason} ${citations(e.source_ids)}.`);
const output = lines.join('\n') + '\n';
const target = new URL('../CATALOG.md', import.meta.url);
if (process.argv.includes('--check')) {
  let existing = '';
  try { existing = readFileSync(target, 'utf8'); } catch { /* missing index is stale */ }
  if (existing !== output) { console.error('CATALOG.md is stale. Run npm run build:index.'); process.exitCode = 1; }
  else console.log('CATALOG.md is current.');
} else {
  writeFileSync(target, output);
  console.log('Generated CATALOG.md.');
}
